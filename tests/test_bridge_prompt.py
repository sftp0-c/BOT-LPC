"""Мост не должен разъезжаться с проектом: три вещи, которые это стерегут.

Что здесь проверяется.

1. Задание уходит в opencode КАК ЕСТЬ, без вводной. Инструкции лежат в
   AGENTS.md, и opencode читает его сам - проверено на живом запуске. Пока
   вводная была в тексте задания, модель путала её с письмом владельца: то
   отвечала «твоё сообщение обрывается на слове “пишет”» (это было из инструкций),
   то «я готов принимать инструкции». Менялись формулировки, суть не менялась:
   письмо должно оставаться письмом. Тест нужен, чтобы никто не вернул обёртку
   «на всякий случай».

2. AGENTS.md существует и в нём ключевые правила. Файл исчезнет - и мост снова
   станет отвечать «я пока ничего не делал», а это будет выглядеть как поломка
   модели, а не как отсутствие инструкций.

3. Сессия запоминается. Без неё каждое задание начинается с нуля, и связь между
   заданиями теряется - владелец получает «это первое сообщение в нашем
   разговоре».

4. Номер сессии берётся из ответа, а не выдумывается: opencode отвергает
   несуществующие идентификаторы, и это проверено на живом запуске.
"""
import json
import re
from pathlib import Path

import pytest

import bridge_worker as worker

ROOT = Path(__file__).resolve().parents[1]


# ── 1. задание уходит как есть ─────────────────────────────────────────────
def test_в_программе_нет_вводной():
    """Инструкции живут в AGENTS.md, и в программе их быть не должно.

    Проверяем исходник, а не поведение: обёртка может не влиять на текущий ответ
    и при этом ломать следующий, поэтому ловим появление в коде.
    """
    исходник = Path(worker.__file__).read_text(encoding="utf-8-sig")
    assert "PREAMBLE" not in исходник, (
        "в программе снова появилась вводная в задании. Она путается с письмом "
        "владельца: модель принимает её за сообщение и отвечает не на задание."
    )


def test_задание_уходит_дословно():
    """В команде задание передаётся отдельным аргументом, без обёрток."""
    исходник = Path(worker.__file__).read_text(encoding="utf-8-sig")
    assert re.search(r"command\s*\+\s*\[task\]", исходник), (
        "задание передаётся не как есть. Проверь, не появилась ли снова вводная."
    )
    assert "ЗАДАЧА:" not in исходник
    assert "задание_от_владельца" not in исходник


# ── 2. AGENTS.md на месте и содержателен ───────────────────────────────────
def test_файл_инструкций_существует():
    путь = ROOT / "AGENTS.md"
    assert путь.exists(), (
        "нет AGENTS.md. opencode читает его сам, и без него мост не знает, кто он "
        "и на каком языке отвечать - начинаются ответы вроде «я ничего не делал»."
    )
    assert len(путь.read_text(encoding="utf-8-sig").strip()) > 400, "файл почти пустой"


@pytest.mark.parametrize("правило", [
    ("pytest", "правило про запуск проверок"),
    ("ruff", "правило про линтер"),
    ("pre-push", "правило про бекап перед пушем"),
    ("по-русски", "правило про язык"),
    ("STATE.md", "указание, что читать в начале"),
])
def test_в_файле_есть_ключевые_правила(правило: tuple):
    слово, описание = правило
    текст = (ROOT / "AGENTS.md").read_text(encoding="utf-8-sig").lower()
    assert слово.lower() in текст, f"в AGENTS.md нет {описание}"


def test_в_файле_есть_правило_про_мост():
    """Ответ читают с телефона - это надо сказать, иначе отчёты выходят длинными."""
    текст = (ROOT / "AGENTS.md").read_text(encoding="utf-8-sig")
    assert "MAX" in текст, "в AGENTS.md нет ничего про ответы через MAX"
    assert "коротко" in текст.lower() or "кратко" in текст.lower(), \
        "в AGENTS.md нет требования к краткости ответа"


# ── 3. сессия ──────────────────────────────────────────────────────────────
def test_номер_сессии_берётся_из_ответа():
    вывод = "\n".join([
        json.dumps({"type": "step_start", "sessionID": "ses_abc123", "part": {}}),
        json.dumps({"type": "text", "sessionID": "ses_abc123",
                    "part": {"messageID": "msg_1", "text": "ответ"}}),
    ])
    assert worker.session_of(вывод) == "ses_abc123"


def test_номер_берётся_даже_когда_нет_текста():
    """Заход может не дать текста, но номер сессии в событиях всё равно есть."""
    вывод = json.dumps({"type": "step_start", "sessionID": "ses_xyz", "part": {}})
    assert worker.session_of(вывод) == "ses_xyz"


def test_без_номера_не_выдумываем():
    """Нет номера - нет номера. opencode выдуманные идентификаторы не берёт."""
    assert worker.session_of("") == ""
    assert worker.session_of("просто текст") == ""
    assert worker.session_of(json.dumps({"type": "text", "sessionID": ""})) == ""


def test_не_session_в_счёт_не_идёт():
    """Берём только те, что начинаются с ses: мусорный номер пригодился бы хуже."""
    assert worker.session_of(json.dumps({"sessionID": "не-сессия"})) == ""


def test_запоминается_только_при_смене(tmp_path):
    """Настройки пишутся в файл, лишние записи на каждом задании - только шум."""
    настройки = {"session": "ses_old", "panel_url": "x"}
    worker.save_settings = lambda data: Path(tmp_path / "s.json").write_text(
        json.dumps(data, ensure_ascii=False), encoding="utf-8")
    worker.remember_session(настройки, json.dumps({"sessionID": "ses_old"}))
    assert настройки["session"] == "ses_old", "перезаписали тем же самым"
    worker.remember_session(настройки, json.dumps({"sessionID": "ses_new"}))
    assert настройки["session"] == "ses_new"


def test_разбор_берёт_последнюю_реплику():
    """Две реплики подряд - берём вторую. Первая была черновиком.

    Без этого ответ удваивался: «давай осмотрюсь» + сам ответ.
    """
    вывод = "\n".join([
        json.dumps({"type": "text", "part": {"messageID": "msg_1", "text": "Дай осмотрюсь. "}}),
        json.dumps({"type": "text", "part": {"messageID": "msg_2", "text": "Готово."}}),
    ])
    assert worker._answer_from(вывод) == "Готово."


def test_куски_одной_реплики_склеиваются():
    """Один messageID - одна реплика, даже из нескольких кусков."""
    вывод = "\n".join([
        json.dumps({"type": "text", "part": {"messageID": "msg_1", "text": "Сделал "}}),
        json.dumps({"type": "text", "part": {"messageID": "msg_1", "text": "и проверил."}}),
    ])
    assert worker._answer_from(вывод) == "Сделал и проверил."


def test_без_идентификатора_склеивается_всё():
    """Если messageID не пришёл, ведём себя как раньше: склеиваем все куски.

    Иначе пришлось бы выбрасывать куски настоящей реплики.
    """
    вывод = "\n".join([
        json.dumps({"type": "text", "part": {"text": "раз"}}),
        json.dumps({"type": "text", "part": {"text": "два"}}),
    ])
    assert worker._answer_from(вывод) == "раздва"
