"""Порт моста обязан быть недоступен из сети - это теперь главная защита.

Что изменилось и почему здесь проверка. Проверка «запрос с этой машины» внутри
бота не работала: Docker Desktop публикует порт через виртуальную машину, и бот
видит адрес её шлюза даже для запроса с этой же машины. Мост с этой машины
получал отказ, то есть не работал вовсе.

Ослабить проверку до «шлюза» - значит не проверять ничего: любой запрос из
локальной сети приходит тем же адресом, а порт 8080 открыт ещё и в туннель,
то есть в интернет. Тогда единственной защитой служебных адресов остался бы
токен, а по его утечке (лог, скриншот, копия .env) очередь становилась бы
доступна постороннему.

Поэтому граница перенесена на хост: порт моста публикуется как
`127.0.0.1:8090:8090`, и система не принимает на нём соединений из сети. Это
проверка на уровне системы, её нельзя обойти подменой заголовка или адреса.

Ошибка в одном символе (0.0.0.0 вместо 127.0.0.1) тихо возвращает мост в
интернет, и ни один тест этого не заметит - если не проверять здесь. Поэтому
проверка есть.

Что ещё проверяется: по общему порту 8080 служебные адреса недоступны вовсе,
потому что они живут в отдельном приложении.
"""
import re
from pathlib import Path


import bridge_service
import config

COMPOSE = Path("docker-compose.yml")
DOCKERFILE = Path("Dockerfile")


def published_ports() -> list:
    """Публикации портов из docker-compose.yml в виде (адрес, порт_контейнера).

    Публикация записывается тремя частями: `адрес:порт_хоста:порт_контейнера`.
    Адрес - IPv4, без двоеточий, поэтому границы однозначны и разбирать надо все
    три части, а не пытаться угадать где кончится адрес: закрывающая кавычка в
    регулярке заставляет напарываться на последнее двоеточие, и хост тогда
    выходит вида "127.0.0.1:8090" вместо "127.0.0.1".
    """
    text = COMPOSE.read_text(encoding="utf-8")
    found = re.findall(r'^\s*-\s*"([^:"]+):(\d+):(\d+)"', text, re.M)
    return [(host, container) for host, _host_port, container in found]


# ── граница доступа ────────────────────────────────────────────────────────
def test_bridge_port_is_not_published_to_the_network():
    """Порт моста слушает только локально. Это и есть граница доступа."""
    bridge_ports = [host for host, port in published_ports() if port == "8090"]
    assert bridge_ports, "порт моста вообще не опубликован - мост не заработает"
    assert bridge_ports == ["127.0.0.1"], (
        f"порт моста опубликован на {bridge_ports}, а должен быть только на 127.0.0.1. "
        "Это открывает очередь заданий в локальную сеть и в туннель."
    )


def test_bridge_port_is_passed_into_the_container():
    assert re.search(r"^\s*BRIDGE_PORT:\s*8090\s*$",
                     COMPOSE.read_text(encoding="utf-8"), re.M), \
        "порт моста не передан в контейнер"


def test_panel_port_stays_available_to_the_network():
    """Основной порт должен остаться открытым: панелью пользуются из сети.

    Обратная проверка, чтобы исправление не ушло в другую сторону - закрыть
    панель было бы не меньшей ошибкой.
    """
    hosts = [host for host, port in published_ports() if port == "8080"]
    assert hosts == ["0.0.0.0"], f"панель на {hosts} - её должно быть видно из сети"


# ── мост не висит на общем порту ───────────────────────────────────────────
def test_bridge_addresses_are_not_in_the_main_app():
    """По общему порту 8080 адресов моста нет вовсе.

    Проверка поведением, а не подсчётом маршрутов: эта версия FastAPI подключает
    роутер лениво одним объектом, и перечень app.routes не показывает реальные
    адреса. Проверка структуры зависит от версии библиотеки и уже соврала.
    """
    from fastapi.testclient import TestClient

    import bot

    assert TestClient(bot.app).get("/bridge/next").status_code == 404, (
        "служебные адреса моста отвечают по общему порту 8080, который открыт в "
        "локальную сеть и в туннель"
    )


def test_bridge_service_serves_its_addresses():
    """Служба моста отвечает на свои адреса.

    Без токена - отказ, но не «адреса нет»: 403 вместо 404 означает, что адрес
    существует и охраняется токеном.
    """
    from fastapi.testclient import TestClient

    assert TestClient(bridge_service.app).get("/bridge/next").status_code == 403, \
        "адреса моста не на месте в службе моста"


def test_bridge_service_does_not_serve_the_panel():
    """В службе моста нет адресов панели - иначе граница снова дырявая.

    Служба моста поднимается на порту, доступном любому процессу на этой машине.
    Если в ней окажется панель, то доступ к обращениям и сотрудникам получает
    всё, что запущено локально, минуя пароль сис-админа.
    """
    from fastapi.testclient import TestClient

    client = TestClient(bridge_service.app)
    for path in ("/panel", "/panel/tickets", "/panel/access", "/panel/login"):
        assert client.get(path).status_code == 404, (
            f"в службе моста отвечает адрес панели {path}: мост не должен её "
            "поднимать, порт слушает любой локальный процесс"
        )


# ── настройки ──────────────────────────────────────────────────────────────
def test_bridge_still_needs_a_token():
    """Токен остаётся обязательным, даже при закрытом порте.

    Порт закрыт снаружи, но любой процесс на этой машине до него дотянется.
    """
    assert "BRIDGE_TOKEN" in config.__doc__ or hasattr(config, "BRIDGE_TOKEN")
    assert hasattr(config, "BRIDGE_ENABLED")
    assert not hasattr(config, "BRIDGE_LOCAL_HOSTS"), (
        "BRIDGE_LOCAL_HOSTS вернулся: проверка адреса клиента внутри бота не "
        "работает с Docker и сломает мост"
    )


# ── контейнер запускает обе службы ─────────────────────────────────────────
def test_container_starts_both_services():
    command = DOCKERFILE.read_text(encoding="utf-8")
    assert "bridge_service:app" in command, "в образе не запускается служба моста"
    assert re.search(r"exec uvicorn bot:app", command), (
        "бот перестал быть ведущей службой - контейнер завершится вместе с ним"
    )


def test_bridge_service_is_copied_into_the_image():
    assert "bridge_service.py" in DOCKERFILE.read_text(encoding="utf-8"), \
        "bridge_service.py не копируется в образ - контейнер не поднимется"
