"""Проверка подписи MAX для мини-приложения.

Самая ценная проверка здесь - сверка с примером из официальной документации
MAX (docs/webapps/validation). Он там приведён целиком, включая «подготовленные
данные» - строку, которую MAX подписывает. Значит разбор и построение строки
подписи проверяются не моим пониманием, а чужим, заведомо верным примером.

Чего эти проверки не доказывают
-------------------------------
Строка из документации подписана placeholder-ом <calculated_hash>, а не
настоящей подписью MAX. Поэтому проверка подписи у нас круговая: правильный
ввод даёт верный выход, но совпадение байт в байт с живым MAX отсюда не следует.
Проверяется это один раз - когда мини-приложение впервые откроют по-настоящему.
До тех пор порог невысокий, и об этом честнее сказать, чем делать вид, что
подпись проверена.

Декодирование двухуровневое, и это главная ловушка: внешний слой браузер
разворачивает сам, а внутри значения развёрнуты ещё раз. Модуль обязан снять
ровно один слой.
"""
from urllib.parse import quote, unquote

import pytest

import maxapp

ТОКЕН = "1234567890:FAKE_TOKEN_FOR_TESTS"

# Строка из документации MAX - ровно как там, кодированная внешним слоем.
ДОК_ФРАГМЕНТ = (
    "chat%3D%257B%2522id%2522%253A12345%252C%2522type%2522%253A%2522DIALOG%2522%257D"
    "%26ip%3D192.168.0.1"
    "%26user%3D%257B%2522id%2522%253A67890%252C%2522first_name%2522%253A%2522Max%2522"
    "%252C%2522last_name%2522%253A%2522User%2522%252C%2522username%2522%253Anull"
    "%252C%2522language_code%2522%253A%2522ru%252C%2522photo_url%2522%253Anull%257D"
    "%26query_id%3D4c0ab423-342b-4e45-aea4-2747dbc500cd"
    "%26auth_date%3D1771409719"
    "%26hash%3D%3Ccalculated_hash%3E"
)

# Готовая строка для подписи из той же документации.
ДОК_CHECK_STRING = (
    'auth_date=1771409719\n'
    'chat={"id":12345,"type":"DIALOG"}\n'
    'ip=192.168.0.1\n'
    'query_id=4c0ab423-342b-4e45-aea4-2747dbc500cd\n'
    'user={"id":67890,"first_name":"Max","last_name":"User",'
    '"username":null,"language_code":"ru","photo_url":null}'
)


def init_data_из_документации() -> str:
    """Что отдаёт браузер: внешний слой развёрнут, внутренние значения нет."""
    return unquote(ДОК_ФРАГМЕНТ)


def init_data_с_исправленным_user() -> str:
    """Тот же пример из документации, но поле user перекодировано без опечатки."""
    import json

    пользователь = {"id": 67890, "first_name": "Max", "last_name": "User",
                    "username": None, "language_code": "ru", "photo_url": None}
    разговор = '{"id":12345,"type":"DIALOG"}'
    параметры = [
        f"chat={quote(разговор)}",
        "ip=192.168.0.1",
        f"user={quote(json.dumps(пользователь, ensure_ascii=False, separators=(',', ':')))}",
        "query_id=4c0ab423-342b-4e45-aea4-2747dbc500cd",
        "auth_date=1771409719",
        "hash=<calculated_hash>",
    ]
    return "&".join(параметры)


def живая_строка(пользователь=67890, токен=ТОКЕН, **прочие) -> str:
    """Собирает initData с настоящей подписью нашего модуля."""
    import json

    части = [f"user={quote(json.dumps({'id': пользователь}, separators=(',', ':')))}",
             f"auth_date={прочие.get('auth_date', 1771409719)}"]
    for ключ, значение in прочие.items():
        if ключ == "auth_date":
            continue
        части.append(f"{quote(ключ)}={quote(str(значение))}")
    без_подписи = "&".join(части)
    return f"{без_подписи}&hash={maxapp.sign(без_подписи, токен)}"


# ── сверка с документацией ───────────────────────────────────────────────
def test_parses_the_documented_example():
    """Разбор совпадает с примером из документации MAX."""
    параметры = maxapp.parse(init_data_из_документации())

    assert параметры["ip"] == "192.168.0.1"
    assert параметры["query_id"] == "4c0ab423-342b-4e45-aea4-2747dbc500cd"
    assert параметры["auth_date"] == "1771409719"
    assert параметры["chat"] == '{"id":12345,"type":"DIALOG"}'
    # поле user в официальном примере не проверяем целиком: в нём опечатка
    # самой документации, разобранная отдельной проверкой ниже. Здесь убеждаемся
    # лишь, что ключ на месте и идентификатор внутри читается.
    assert параметры["user"].startswith('{"id":67890,')
    assert '"first_name":"Max"' in параметры["user"]


def test_data_check_string_matches_the_documented_one():
    """Строка для подписи - байт в байт как в документации.

    Это главная проверка модуля: она ловит и порядок сортировки, и перевод
    строки между парами, и то, что hash в строку не входит, и двухуровневое
    декодирование сразу. Ошибка в любом из этого тихо ломает подпись у всех.
    """
    # Пример из документации, но с исправленным полем user: в официальном
    # варианте там потеряна кавычка, и строка подписи не совпала бы с той, что
    # показана на той же странице. Всё остальное - дословно из документации.
    получили = maxapp.data_check_string(maxapp.parse(init_data_с_исправленным_user()))

    assert получили == ДОК_CHECK_STRING, (
        "строка для подписи разошлась с документацией:\n"
        f"получили: {получили!r}\nожидали:  {ДОК_CHECK_STRING!r}")


def test_user_id_comes_from_the_documented_example():
    """ID человека достаётся из JSON в user и приходит строкой.

    Здесь user уже исправленный: в официальном примере потеряна закрывающая
    кавычка после "ru", см. проверку про опечатку в документации ниже.
    """
    параметры = maxapp.parse(init_data_с_исправленным_user())

    assert maxapp.user_id(параметры) == "67890"


def test_documented_example_loses_a_quote_in_the_user_field():
    """Опечатка в примере документации MAX: user не разбирается как JSON.

    Официальный пример в docs/webapps/validation содержит

        ...%2522language_code%2522%253A%2522ru%252C%2522photo_url%2522...

    и после декодирования даёт "language_code":"ru,"photo_url":null} - закрывающей
    кавычки после ru нет, и это не валидный JSON. На той же странице, в
    «подготовленных данных», кавычка стоит правильно: пример противоречит сам
    себе.

    Проверяем не «правильность» примера, а то, что наш код на таком вводе
    возвращает пустой ID и не падает. Если MAX исправит документацию, тест об
    этом сообщит - и его надо будет переписать, а не молча оставить зелёным.
    """
    параметры = maxapp.parse(init_data_из_документации())

    assert '"language_code":"ru,"photo_url":null}' in параметры["user"], \
        "опечатка в примере документации исчезла - пример пора перепроверить"
    assert maxapp.user_id(параметры) == "", "битый JSON не должен давать ID"


# ── подпись ─────────────────────────────────────────────────────────────
def test_secret_key_is_hmac_of_bot_token():
    """Ключ считается как в документации: HMAC-SHA256 от токена с ключом WebAppData."""
    import hashlib
    import hmac

    ожидаемый = hmac.new(b"WebAppData", ТОКЕН.encode(), hashlib.sha256).digest()

    assert maxapp.secret_key(ТОКЕН) == ожидаемый
    assert maxapp.secret_key(ТОКЕН) != maxapp.secret_key(ТОКЕН + "x"), \
        "ключ не зависит от токена"


def test_valid_signature_passes():
    """Своя подпись проходит и возвращает параметры."""
    строка = живая_строка()

    параметры = maxapp.verify(строка, ТОКЕН)

    assert параметры is not None, "своя подпись не прошла"
    assert maxapp.user_id(параметры) == "67890"


def test_hash_is_not_part_of_the_signed_string():
    """hash не входит в подписываемую строку - иначе подпись не сойдётся."""
    строка = живая_строка()
    параметры = maxapp.parse(строка)

    assert "hash" not in maxapp.data_check_string(параметры)
    assert "hash=" not in maxapp.data_check_string(параметры)


def test_tampered_field_is_rejected():
    """Изменённое поле ломает подпись.

    Самая важная проверка безопасности: если бы подпись считалась не по тому,
    что прислали, человек подставил бы чужой user и получил бы чужие данные.
    """
    строка = живая_строка(пользователь=67890)
    подмена = строка.replace("67890", "99999")

    assert maxapp.verify(подмена, ТОКЕН) is None, \
        "подмена чужого ID прошла проверку"


def test_signature_from_another_token_is_rejected():
    """Подпись, сделанная чужим токеном, не проходит."""
    строка = живая_строка(токен="чужой-токен")

    assert maxapp.verify(строка, ТОКЕН) is None


def test_missing_hash_is_rejected():
    """Без hash проверка невозможна, и это не ошибка."""
    assert maxapp.verify("user=%7B%22id%22%3A1%7D&auth_date=1", ТОКЕН) is None


def test_empty_token_is_rejected():
    """Без токена проверка не проходит ничего, даже с верной подписью."""
    строка = живая_строка()

    assert maxapp.verify(строка, "") is None


def test_duplicate_key_is_rejected():
    """Повторяющийся параметр бракуется - так требует документация.

    Проверка важна тем, что словарь повтор схлопывает молча: подпись считалась
    бы по одной копии, а прислали две.
    """
    строка = живая_строка()
    с_повтором = строка + "&auth_date=999"

    assert maxapp.повторяются_ли_ключи(с_повтором), "повтор ключа не замечен"
    assert not maxapp.повторяются_ли_ключи(строка), "ложный повтор там, где его нет"
    assert maxapp.verify(с_повтором, ТОКЕН) is None, "подпись с повтором прошла"


@pytest.mark.parametrize(" мусор", ["", "   ", "просто текст", "=", "a=1&", "&&&",
                                   "hash=", "%", "user=%7B"])
def test_garbage_does_not_crash(мусор):
    """Мусор во входе даёт None, а не исключение."""
    assert maxapp.verify(мусор, ТОКЕН) is None


def test_user_id_survives_broken_json():
    """Битый JSON в user - это пустой ID, а не падение."""
    assert maxapp.user_id({"user": "{не json"}) == ""
    assert maxapp.user_id({"user": "[]"}) == ""
    assert maxapp.user_id({"user": ""}) == ""


def test_start_param_is_read():
    """Значение из ?startapp= доступно - им открывают нужный экран."""
    параметры = maxapp.parse(живая_строка(start_param="group_2528"))

    assert maxapp.start_param(параметры) == "group_2528"


# ── обёртка для роутов ───────────────────────────────────────────────────
def test_проверка_returns_id_and_params():
    """Удобная обёртка отдаёт ID и параметры."""
    строка = живая_строка(пользователь=46010397)

    человек, параметры = maxapp.проверка(строка, ТОКЕН)

    assert человек == "46010397"
    assert параметры["auth_date"]


def test_проверка_raises_on_foreign_data():
    """Чужие данные - исключение, а не пустой ID.

    Разница существенная: роут на пустом ID должен остановиться, а не отдать
    страницу «вы не авторизованы» как будто всё в порядке.
    """
    with pytest.raises(ValueError):
        maxapp.проверка("user=%7B%22id%22%3A1%7D&hash=непонятно", ТОКЕН)


def test_проверка_raises_when_no_user_in_signature():
    """Подпись верная, но человека в ней нет - тоже отказ."""
    без_пользователя = "auth_date=1771409719"
    строка = f"{без_пользователя}&hash={maxapp.sign(без_пользователя, ТОКЕН)}"

    assert maxapp.verify(строка, ТОКЕН), "подпись должна быть верной"
    with pytest.raises(ValueError):
        maxapp.проверка(строка, ТОКЕН)