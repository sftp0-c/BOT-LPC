"""Проверки: кабинет каждой подгруппы, «пара» вместо «урока», звонки.

Задача владельца
----------------
«Кабинеты у подгрупп было видно, фамилии и инициалы преподавателей тоже было
видно. Чтобы на глаз всё понятно.»

Данные взяты из настоящего PDF колледжа, который лежит в кэше на сервере:
путь /app/data/schedules/23-29_6fbbeacf5110eb3c.pdf. Ячейка подгрупповой пары
выглядит так - предмет в одной колонке, аудитория в соседней, по строке на
подгруппу:

    1.МДК.03.01 ТРТОУ   |  РММ
    (лабораторная)      |  313-1
    Ибрагимов Р. Т.     |
    2.ИнЯзык в ПрофД    |
    (лабораторная)      |
    Власова Л. Н.       |

Что проверяем
-------------
1. Подгрупп ровно две, у каждой свой предмет, свой преподаватель и СВОЙ кабинет.
   Раньше кабинет брался только первый, и второй терялся.
2. Если кабинет один на всех - достаётся каждой подгруппе.
3. Вид занятия приклеен к предмету, а не стоит отдельным куском через «|».
4. Фамилия и инициалы преподавателя видны в тексте.
5. Урок -> пара по официальному графику владельца (7 пар, 11 уроков).
6. В строке звонков времена пар не повторяются.
"""
import datetime as dt

import timetable as tt

# Настоящая ячейка из PDF колледжа: подгруппы 1 и 2, у каждой свой кабинет.
ЯЧЕЙКА_ПОДГРУПП = (
    "1.МДК.03.01 ТРТОУ\n"
    "(лабораторная)\n"
    "Ибрагимов Р. Т.\n"
    "2.ИнЯзык в ПрофД\n"
    "(лабораторная)\n"
    "Власова Л. Н."
)
ЯЧЕЙКА_АУДИТОРИЙ = "РММ\n313-1"


def страница(колонка_предмета: str, колонка_аудитории: str, номер: str = "1") -> dict:
    """Страница с таблицей «№ | группа | ауд.» - как в PDF колледжа."""
    шапка = ["№", "24-25", "", "Ауд."]
    return {"text": "День - Понедельник, 05.10.2026",
            "tables": [[шапка, ["", "Предмет, вид занятия, преподаватель", "Ауд."],
                        [номер, колонка_предмета, колонка_аудитории]]]}


def разобрать(предмет: str, аудитории: str, группа: str = "24-25") -> list[tt.Lesson]:
    расписание = tt.build_schedule([страница(предмет, аудитории)], группа)
    return [урок for день in расписание.days.values() for урок in день.lessons]


# ── 1. кабинет каждой подгруппы ────────────────────────────────────────────
def test_у_каждой_подгруппы_свой_кабинет():
    """Главное требование владельца.

    В PDF в ячейке аудитории столько строк, сколько подгрупп: «РММ» первой,
    «313-1» второй. Раньше parse_room брал только первый кусок, и кабинет
    второй подгруппы просто исчезал из расписания.
    """
    уроки = разобрать(ЯЧЕЙКА_ПОДГРУПП, ЯЧЕЙКА_АУДИТОРИЙ)
    assert len(уроки) == 1, f"урок не разобран: {уроки}"
    части = уроки[0].split_parts()

    assert len(части) == 2, f"подгрупп {len(части)}, ждали 2: {части}"
    assert части[0].room == "РММ", f"кабинет первой подгруппы: {части[0].room!r}"
    assert части[1].room == "313-1", f"кабинет второй подгруппы потерян: {части[1].room!r}"


def test_второй_кабинет_не_пропадает_из_текста():
    """Оба кабинета должны быть видны студенту в тексте расписания."""
    уроки = разобрать(ЯЧЕЙКА_ПОДГРУПП, ЯЧЕЙКА_АУДИТОРИЙ)
    текст = уроки[0].line()

    assert "РММ" in текст, текст
    assert "313-1" in текст, f"второй кабинет не показан: {текст}"


def test_фамилия_и_инициалы_преподавателей_видны():
    """Второе требование: преподаватель должен быть виден."""
    уроки = разобрать(ЯЧЕЙКА_ПОДГРУПП, ЯЧЕЙКА_АУДИТОРИЙ)
    части = уроки[0].split_parts()
    текст = уроки[0].line()

    assert части[0].teacher == "Ибрагимов Р. Т.", части[0].teacher
    assert части[1].teacher == "Власова Л. Н.", части[1].teacher
    assert "Ибрагимов Р. Т." in текст, текст
    assert "Власова Л. Н." in текст, текст


def test_один_кабинет_на_всех_подгрупп():
    """Когда аудитория одна, она достаётся каждой подгруппе."""
    уроки = разобрать(ЯЧЕЙКА_ПОДГРУПП, "205-2")
    части = уроки[0].split_parts()

    assert len(части) == 2
    assert части[0].room == части[1].room == "205-2"


# ── 2. вид занятия приклеен к предмету ─────────────────────────────────────
def test_вид_занятия_не_отдельный_предмет():
    """«(лабораторная)» относится к предмету над собой.

    Раньше строка «(«) начинала новый блок, подгрупповая ячейка рвалась на
    четыре части, и из-за этого кабинеты раскидывались мимо своих подгрупп.
    """
    части = tt.parse_cell_parts(ЯЧЕЙКА_ПОДГРУПП)

    assert len(части) == 2, f"частей {len(части)}, ждали 2: {части}"
    assert части[0][0] == "1.МДК.03.01 ТРТОУ (лабораторная)", части[0][0]
    assert части[1][0] == "2.ИнЯзык в ПрофД (лабораторная)", части[1][0]


def test_в_тексте_нет_вертикальной_черты():
    """Черта «|» больше не мусорит в предмете - её не должно быть в строке."""
    уроки = разобрать(ЯЧЕЙКА_ПОДГРУПП, ЯЧЕЙКА_АУДИТОРИЙ)
    текст = уроки[0].line()

    assert "| (лабораторная)" not in текст, текст
    assert "(лабораторная)" in текст, текст


def test_аудитория_помечена():
    """«305-1» без пометки неотличимо от времени или номера пары."""
    уроки = разобрать(ЯЧЕЙКА_ПОДГРУПП, ЯЧЕЙКА_АУДИТОРИЙ)
    assert "ауд. РММ" in уроки[0].line()


# ── 3. урок -> пара по официальному графику ────────────────────────────────
def test_урок_даёт_номер_пары():
    """Официальный график: 7 пар, 11 уроков. Первые четыре пары - по два урока."""
    раскладка = [tt.pair_of_lesson(n) for n in range(1, 12)]
    assert раскладка == [1, 1, 2, 2, 3, 3, 4, 4, 5, 6, 7], раскладка


def test_время_пары_по_официальному_графику():
    """Времена взяты со скрина владельца, сверил построчно."""
    ожидаемое = ["08:00–09:35", "09:50–11:40", "12:00–13:50", "14:00–15:35",
                 "15:45–17:15", "17:25–18:55", "19:00–20:30"]
    получено = [tt.pair_time(n) for n in range(1, tt.PAIR_COUNT + 1)]
    assert получено == ожидаемое, получено


def test_времена_пар_не_повторяются():
    """Раньше пара 1 и пара 2 выходили с одинаковым временем.

    pair_time искал интервал по номеру УРОКА, а пара (1, 2) подходила и первому,
    и второму. Теперь номер пары - индекс в PAIR_SPANS.
    """
    времена = [tt.pair_time(n) for n in range(1, tt.PAIR_COUNT + 1)]
    assert len(set(времена)) == len(времена), времена


def test_строка_звонков_разборчива():
    """В неделе строка звонков не пересекается и не обрезается."""
    день = tt.DaySchedule(weekday=0, lessons=[
        tt.Lesson(number=1, subject="Предмет", parts=[tt.LessonPart("Предмет")])])
    неделя = tt.GroupSchedule(group="ИС-21", week=dt.date(2026, 10, 5), days={0: день})
    текст = tt.format_schedule(неделя)
    строки = [x for x in текст.split("\n") if x.startswith("Пары по звонкам:")]

    assert строки, текст
    assert "…" not in строки[0], f"строка звонков обрезана: {строки[0]}"
    # каждое время пары встречается ровно один раз
    for номер in range(1, tt.PAIR_COUNT + 1):
        время = tt.pair_time(номер)
        if время:
            assert строки[0].count(время) == 1, f"время {время} встречается дважды"


# ── 4. пустая пара не теряется ────────────────────────────────────────────
def test_урок_без_аудитории_не_ломает_строку():
    """Аудитории может не быть - тогда строка просто короче."""
    уроки = разобрать("Математика\n(лекция)\nИванова А. А.", "")
    текст = уроки[0].line()

    assert "ауд." not in текст, текст
    assert "Иванова А. А." in текст, текст
    # предмет, время и номер - на месте, строка не развалилась
    assert "1. 08:00–08:45  Математика (лекция)" in текст, текст



# ── 5. обычная ячейка не ломается ──────────────────────────────────────────
def test_обычная_ячейка_даёт_одну_часть():
    части = tt.parse_cell_parts("МДК.03.01 ОПНиГ\n(лекция)\nКрылова В. И.")
    assert len(части) == 1, части
    assert части[0][0] == "МДК.03.01 ОПНиГ (лекция)", части[0][0]
    assert части[0][1] == "Крылова В. И.", части[0][1]


def test_аудитории_читаются_списком():
    assert tt.parse_rooms("РММ\n313-1") == ["РММ", "313-1"]
    assert tt.parse_rooms("205-2") == ["205-2"]
    assert tt.parse_rooms("") == []