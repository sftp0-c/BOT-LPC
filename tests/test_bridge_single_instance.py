"""Метка «программа уже работает»: второй экземпляр запускаться не должен.

Почему это не замок. Замок занят работой, а не присутствием: между кругами он
свободен. Я попробовал ловить второй экземпляр на нём - и на живом боте второй
не отказался, а работал. Метка поэтому своя.

Что здесь проверяется, и почему именно это.
* Метку нельзя занять, если уже работает живой экземпляр. Иначе два круга в
  одной очереди: лишние вызовы модели и путаница в журнале, кому принадлежит
  ответ.
* Мёртвый держатель НЕ считается работающим. Это важнейшее: программа
  заканчивается аварийно нередко, и проверка без этого условия сделала бы
  перезапуск невозможным навсегда.
* Мусор в файле метки тоже не считается работой - иначе после неудачного
  завершения записи мост не поднялся бы.
* Свою метку отпускаем, чужую - нет.
"""
import os
import subprocess
import sys

import bridge_worker
from bridge_lock import pid_alive

OWNER = bridge_worker.SingleInstance


def живые(pid_который_умер: bool = False):
    """Подмена проверки живости: надо управлять, а не гадать."""
    return lambda _pid: not pid_который_умер


# ── пусто и мусор ──────────────────────────────────────────────────────────
def test_метки_нет_никто_не_работает(tmp_path):
    метка = OWNER(tmp_path / "worker.pid")
    assert метка.holder() == ""
    assert метка.take() is True


def test_мусор_в_метке_не_считается_работой(tmp_path):
    """Испорченный файл метки - это «никто не работает», а не «работает неизвестно»."""
    путь = tmp_path / "worker.pid"
    путь.write_text("не число", encoding="utf-8")
    assert OWNER(путь).holder() == ""


def test_пустой_файл_метки_не_считается_работой(tmp_path):
    путь = tmp_path / "worker.pid"
    путь.write_text("   \n", encoding="utf-8")
    assert OWNER(путь).holder() == ""


def test_неположительный_номер_не_работа(tmp_path):
    путь = tmp_path / "worker.pid"
    путь.write_text("0", encoding="utf-8")
    assert OWNER(путь).holder() == ""


# ── живой и мёртвый ───────────────────────────────────────────────────────
def test_живой_процесс_занимает_метку(tmp_path):
    """Занятая метка: в файле наш номер, и holder() при этом пуст.

    Тут важно не перепутать два разных вопроса. holder() спрашивает «работает ли
    ДРУГОЙ экземпляр», и свой собственный номер он игнорирует намеренно: иначе
    программа, взявшая метку, сочла бы себя вторым экземпляром и отказалась бы
    работать. А в файле наш номер есть, и он живой.
    """
    метка = OWNER(tmp_path / "worker.pid")
    assert метка.take() is True
    номер = int(метка.path.read_text(encoding="utf-8"))
    assert номер == os.getpid(), "метка записана чужим номером"
    assert pid_alive(номер) is True, "тест запущен в мёртвом процессе, проверка бессмысленна"
    assert метка.holder() == "", "свой номер не должен считаться другим экземпляром"


def test_второй_экземпляр_не_занимает(tmp_path, monkeypatch):
    """Главное правило: пока первый работает, второй не должен занимать метку.

    Настоящий номер процесса запоминается ДО подмены: подмена нужна, чтобы
    изобразить второй экземпляр, и после неё os.getpid уже не ответ на вопрос
    «кто записал в метку».
    """
    путь = tmp_path / "worker.pid"
    настоящий = os.getpid()
    первый = OWNER(путь)
    assert первый.take() is True
    assert int(путь.read_text(encoding="utf-8")) == настоящий

    # Второй экземпляр - это другой процесс, поэтому подменяем и его номер
    monkeypatch.setattr(bridge_worker.os, "getpid", lambda: 424242)
    второй = OWNER(путь)
    assert второй.holder() == str(настоящий), "работающий экземпляр не виден"
    assert второй.take() is False, "второй экземпляр занял метку"
    assert int(путь.read_text(encoding="utf-8")) == настоящий, "запись перебили"


def test_мёртвый_процесс_не_мешает_запуску(tmp_path):
    """После аварийного завершения программа обязана запуститься снова.

    Для этого запускаем короткоживущий процесс, ждём его и записываем его номер.
    Если бы проверка не смотрела на живость, мост после сбоя не поднялся бы
    никогда - и это выглядело бы как «сломался», а не как «осталась запись».
    """
    путь = tmp_path / "worker.pid"
    завершившийся = subprocess.Popen([sys.executable, "-c", "pass"])
    завершившийся.wait()
    путь.write_text(str(завершившийся.pid), encoding="utf-8")
    assert pid_alive(завершившийся.pid) is False

    метка = OWNER(путь)
    assert метка.holder() == "", "мёртвый процесс считается работающим"
    assert метка.take() is True, "после сбоя программа не запускается"


def test_свой_номер_не_считается_чужим(tmp_path):
    """Свой собственный номер - это «ещё не занято», а не «занято мной»."""
    путь = tmp_path / "worker.pid"
    путь.write_text(str(os.getpid()), encoding="utf-8")
    метка = OWNER(путь)
    assert метка.holder() == ""
    assert метка.take() is True


# ── освобождение ───────────────────────────────────────────────────────────
def test_отпуск_освобождает_метку(tmp_path):
    метка = OWNER(tmp_path / "worker.pid")
    assert метка.take() is True
    assert метка.path.exists()
    метка.release()
    assert not метка.path.exists()
    assert OWNER(tmp_path / "worker.pid").take() is True


def test_отпуск_не_трогает_чужую_метку(tmp_path, monkeypatch):
    """Снять чужую метку нельзя: иначе второй экземпляр обойдёт защиту."""
    путь = tmp_path / "worker.pid"
    путь.write_text("424242", encoding="utf-8")
    monkeypatch.setattr(bridge_worker.bridge_lock, "pid_alive", lambda _pid: True)
    метка = OWNER(путь)
    метка.release()
    assert путь.exists(), "чужая метка снесена"
    assert путь.read_text(encoding="utf-8") == "424242"


def test_отпуск_отсутствующей_метки_не_ошибается(tmp_path):
    OWNER(tmp_path / "нет.pid").release()          # просто не должно упасть


# ── где лежит метка ────────────────────────────────────────────────────────
def test_метка_рядом_с_настройками_а_не_в_проекте(tmp_path, monkeypatch):
    """В папке проекта метке не место: там токен и пароль, и папка идёт в образ.

    Сама метка секрета не несёт, но рядом с настройками её удалять и читать
    проще, а в образ она попадать не должна.
    """
    monkeypatch.setattr(bridge_worker, "STATE_DIR", tmp_path)
    метка = OWNER()
    assert метка.path.parent == tmp_path
    assert "BOT-LPC" not in str(метка.path)
