"""Регистрация студента: баги, из-за которых человек застревал в диалоге.

Откуда эти проверки. Владелец показал запись экрана: студентка представляется,
бот повторяет приветствие, на вопрос кода группы отвечает тем же текстом и не
даёт ничего написать, а потом вообще начинает регистрацию заново со слов
«Здравствуйте! Это бот колледжа. Кто вы?».

Четыре разные причины, и все четыре надо закрыть тестом, иначе вернётся:

1. Кнопка «✍️ Создать ...» стирает состояние регистрации. Обработчик regnew не
   входит в список кнопок, которые не стирают состояние (STATE_KEEPING_CALLBACKS
   в bot.py), поэтому к моменту обработки имя уже потеряно. Дальше st_reg_group
   видит пустое имя и зовёт start() - регистрация начинается с нуля.
   Студентка при этом не теряет данные, но её выбрасывает в начало, и сверху
   прилетает приветствие, которое она уже читала.

2. Кнопка «✏️ Введу сам» кладёт в состояние ПУСТОЕ имя и сразу просит группу.
   Студентка вводит своё ФИО - и оно уходит в разбор кода группы. Имя человека
   становится названием группы в справочнике. Это самое неприятное: группа
   «ПЕТРОВААННА» появится у сис-админа в списке, и он её потом не найдёт.

3. Потерянное имя должно приводить к повторному вопросу про ФИО, а не к
   перезапуску всей регистрации. Перезапуск - это и есть «приветствие
   повторяется».

4. Группа должна защищать от «похоже на ФИО». Сейчас любой набор букв без
   пробелов проходит как код группы.

Плюс проверка, что приветствие не дублируется: перед регистрацией бот уже
здоровается словом «Здравствуйте», и после сохранения приветствие из настроек
тоже начинается с «Здравствуйте» - человек видит одно и то же дважды.
"""
import pytest

from conftest import press, say

STUDENT = "100"


async def начать_регистрацию(api, имя="Петрова Анна"):
    """Доходит до вопроса про группу. Возвращает текст последнего экрана."""
    await say(STUDENT, "/start")
    await press(STUDENT, "who:student")
    await say(STUDENT, имя)
    return api.last(STUDENT)[1]


async def состояние():
    import database as db
    return await db.get_state(STUDENT)


# ── 1. кнопка «Создать» не должна стирать регистрацию ───────────────────────
async def test_create_group_button_keeps_the_name(api):
    """Нажали «Создать группу» - имя должно уцелеть.

    Проверяем не только экран, но и само состояние: имя лежит в payload
    состояния reg_group. Если оно пропало, регистрация обречена: дальше
    st_reg_group увидит пустое имя и вернёт человека в начало.
    """
    await начать_регистрацию(api)
    session = await состояние()
    assert session["state"] == "reg_group"
    assert session["payload"]["name"] == "Петрова Анна", "до кнопки имя должно лежать в состоянии"

    await press(STUDENT, "regnew:99-99")
    session = await состояние()
    assert session is not None, "состояние регистрации стёрто кнопкой «Создать»"
    if session:
        assert session["payload"].get("name") == "Петрова Анна", \
            f"имя потерялось после нажатия «Создать»: {session}"


async def test_create_group_button_does_not_restart_registration(api):
    """Главный симптом из записи экрана: после «Создать» не должно быть «Кто вы?»."""
    await начать_регистрацию(api)
    await press(STUDENT, "regnew:99-99")
    текст = api.last(STUDENT)[1]
    assert "Кто вы?" not in текст, (
        f"после «Создать» регистрация началась заново: {текст!r}")
    assert "Здравствуйте" not in текст, (
        f"после «Создать» приветствие пришло повторно: {текст!r}")


# ── 2. «Введу сам» должен спрашивать ФИО, а не группу ──────────────────────
async def test_type_your_own_name_asks_for_name_not_group(api):
    """Нажали «Введу сам» - бот должен спросить ФИО, а не код группы.

    Сейчас наоборот: состояние сразу reg_group с пустым именем, и введённое ФИО
    уезжает в разбор кода группы.
    """
    await say(STUDENT, "/start")
    await press(STUDENT, "who:student")
    await press(STUDENT, "regname:")          # кнопка «✏️ Введу сам»
    текст = api.last(STUDENT)[1]
    assert "ФИО" in текст, f"после «Введу сам» спросили не про ФИО: {текст!r}"
    assert "код группы" not in текст.lower(), \
        f"после «Введу сам» сразу спросили группу, хотя ФИО ещё не введено: {текст!r}"


async def test_typed_name_never_becomes_a_group(api):
    """Введённое ФИО не должно попасть в справочник групп.

    Самое неприятное последствие прошлого поведения: имя без пробелов проходит
    проверку кода группы, и группа «ПЕТРОВААННА» появляется в справочнике.
    """
    await say(STUDENT, "/start")
    await press(STUDENT, "who:student")
    await press(STUDENT, "regname:")
    await say(STUDENT, "Петрова Анна")        # человек вводит ФИО
    # если бот не понял, что это ФИО, он не должен завести группу с таким кодом
    import database as db
    # db.all в проекте нет: в базе только run, run_count и one. Поэтому код
    # достаём через _conn напрямую - так же, как это делает репозиторий.
    async with db._conn() as conn:
        # колонка называется group_code, а не code: в таблице groups так
        # (database.py, SCHEMA). Я сперва написал несуществующую code.
        cur = await conn.execute("SELECT group_code FROM groups")
        коды = [row["group_code"] for row in await cur.fetchall()]
    assert not any("ПЕТРОВА" in код.upper() for код in коды), \
        f"имя человека стало кодом группы: {коды}"
    assert not any("ЗНАЮ" in код.upper() for код in коды), \
        f"ответ «не знаю» стал кодом группы: {коды}"


# ── 3. потерянное имя - повторный вопрос, а не перезапуск ──────────────────
async def test_lost_name_asks_again_without_restart(api):
    """Состояние потеряно - спрашиваем ФИО заново, а не начинаем всю регистрацию.

    Путь «Кто вы?» - это именно то, что видели владелец на экране.
    """
    import database as db

    await начать_регистрацию(api)
    # имитируем потерю состояния: состояние есть, но имени в нём нет
    await db.set_state(STUDENT, "reg_group", {})
    await say(STUDENT, "ИС-21")
    текст = api.last(STUDENT)[1]
    assert "Кто вы?" not in текст, f"регистрация перезапущена с нуля: {текст!r}"
    assert "Здравствуйте" not in текст, f"приветствие повторилось: {текст!r}"


# ── 4. группа не должна принимать то, что явно не группа ───────────────────
async def test_group_prompt_rejects_something_that_is_not_a_group(api):
    """Ответ «не знаю» должен получить человеческий ответ, а не тот же вопрос."""
