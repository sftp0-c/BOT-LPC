def test_урок_дальше_звонков_не_теряется(номер):
    """Урок, который колледж уже ставит в расписание, обязан доехать до студента."""
    звонки = tt.normalize_times({str(урок): ["08:00", "08:45"] for урок in range(1, 15)})
    assert len(звонки) == 14, "звонков на 14 уроков не приготовили, проверить нечего"
    страница = _страница(
        ["№", "24-29(П)", ""],
        [["", "Предмет, вид занятия, преподаватель", "Ауд."],
         ["11", "МДК.04.01 ОРОВО\n(лекция)\nЩербак В. А.", "204-2"],
         [str(номер), "МДК.05.01 ОРДНГ\n(лекция)\nНуриева С. Р.", "204-2"]],
    )
    расписание = tt.build_schedule([страница], "24-29(П)", звонки)
    уроки = [урок for день in расписание.days.values() for урок in день.lessons]
    # Урок 11 читается — значит фикстура цела и теряется именно номер выше предела.
    assert [урок.number for урок in уроки] == [11, номер], (
        f"урок {номер} потерялся: предел MAX_LESSONS_PER_DAY = "
        f"{tt.MAX_LESSONS_PER_DAY}, а колледж такие номера уже ставит"
    )


