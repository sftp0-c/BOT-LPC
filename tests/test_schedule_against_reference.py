def test_аудитория_своей_группы_берётся_из_её_колонки():
    """Колонки идут парами «предмет | ауд.», и аудитория соседней группы — не наша."""
    страница = _страница(
        ["№", "25-21", "", "25-23(П)", ""],
        [["", "Предмет, вид занятия, преподаватель", "Ауд.",
          "Предмет, вид занятия, преподаватель", "Ауд."],
         ["1", "Физ-ра\n(лекция)\nХлопецкий А. И.", "Спорт зал",
          "Математика\n(лекция)\nСабирьянова А. Р.", "116-1"]],
    )
    расписание = tt.build_schedule([страница], "25-23(П)")
    уроки = [урок for день in расписание.days.values() for урок in день.lessons]
    assert [(урок.subject, урок.room) for урок in уроки] == [
        ("Математика | (лекция)", "116-1")], "аудитория взята из чужой колонки"


def test_незнакомая_колонка_не_роняет_разбор():
    """Лишняя колонка в шапке не должна ломать разбор.

    Колледж может добавить колонку («Часы», «Форма контроля»). Разбор обязан её
    пережить: уроки находятся, незнакомая шапка просто не группа.
    """
    страница = _страница(
        ["№", "24-29(П)", "", "Часы", ""],
        [["", "Предмет, вид занятия, преподаватель", "Ауд.", "", ""],
         ["1", "Математика\n(лекция)\nСабирьянова А. Р.", "204", "2", ""],
         ["2", "Математика\n(лекция)\nСабирьянова А. Р.", "204", "2", ""]],
    )
    расписание = tt.build_schedule([страница], "24-29(П)")
    уроки = [урок for день in расписание.days.values() for урок in день.lessons]
    assert [урок.number for урок in уроки] == [1, 2]
    assert уроки[0].subject == "Математика | (лекция)"
    assert уроки[0].room == "204", f"аудитория испорчена незнакомой колонкой: {уроки[0].room!r}"


def test_шапка_из_двух_строк_читается_по_номеру_а_не_по_позиции():
    """Под шапкой групп в PDF идёт вторая строка — «Предмет… | Ауд.».

    Эталон пропускает первые две строки таблицы не глядя, и при шапке из одной
    строки потерял бы первый урок. Мы отсекаем строки по номеру урока, поэтому
    вид шапки не важен.
    """
    страница = _страница(
        ["№", "25-21", ""],
        [["", "Предмет, вид занятия, преподаватель", "Ауд."],
         ["1", "Физ-ра\n(лекция)\nХлопецкий А. И.", "Спортзал"]],
    )
    assert tt.build_schedule([страница], "25-21").lessons_count == 1, \
        "первый урок потерялся из-за второй строки шапки"


def test_синтетические_страницы_разбираются():
    """Фикстуры этого файла целы: на каждой находится ровно один урок.

    Отдельный тест не для красоты. Проверки ниже помечены xfail, и сломанная
    фикстура дала бы «ожидаемо не прошло» по неверной причине, а это тихо. Здесь
    фикстуры проверяются без xfail, поэтому ошибка видна сразу.
    """
    страницы = [
        _страница(
            ["№", "25-21", ""],
            [["", "Предмет, вид занятия, преподаватель", "Ауд."],
             ["1", "Физ-ра\n(лекция)\nХлопецкий А. И.", "Спортзал"]]),
        _страница(
            ["№", "24-29(П)", "", "Часы", ""],
            [["", "Предмет, вид занятия, преподаватель", "Ауд.", "", ""],
             ["1", "Математика\n(лекция)\nСабирьянова А. Р.", "204", "2", ""]]),
        _страница(
            ["№", "24-29(П)", "", "24-25", ""],
            [["", "Предмет, вид занятия, преподаватель", "Ауд.",
              "Предмет, вид занятия, преподаватель", "Ауд."],
             ["11", "МДК.05.01 ОРДНГ\n(лекция)\nНуриева С. Р.", "204-2",
              "Физика\n(лекция)\nПетров П. П.", "205"]]),
    ]
    for страница_, код in zip(страницы, ("25-21", "24-29(П)", "24-25")):
        расписание = tt.build_schedule([страница_], код)
        assert расписание.lessons_count == 1, (
            f"фикстура для {код} сломана: найдено {расписание.lessons_count} уроков"
        )


