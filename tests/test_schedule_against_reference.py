def _страница(шапка, строки, текст="День - Понедельник, 28.09.2026"):
    """Страница разбора в том виде, в каком её отдаёт extract_pages.

    Внимание: tables — это список таблиц, а таблица — список строк. На странице
    колледжа таблица одна, и шапка групп входит в неё первой строкой. Соблазн
    вернуть список строк вместо списка таблиц есть, и тогда разбор молча находит
    ноль уроков; целостность фикстур поэтому проверяется отдельно, тестом
    test_синтетические_страницы_разбираются.
    """
    return {"text": текст, "tables": [[шапка, *строки]]}


