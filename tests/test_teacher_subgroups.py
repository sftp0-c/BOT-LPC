# ── разбор в одном месте ─────────────────────────────────────────────────────
def test_utils_and_timetable_split_agree():
    """Оба пути разбора дают одно и то же - иначе студент и сотрудник разойдутся.

    Разбор живёт в utils, потому что store не имеет права импортировать
    timetable (tests/test_store_split.py), а разбирать склейку приходится и
    хранилищу. Проверка на настоящих строках из базы колледжа.
    """
    случаи = [
        # строка из базы: старый разбор, вид занятия отдельной частью
        ("Экономика отрас | (лекция)", "Шкуропатов П. И.", "315-1"),
        # строка из базы: подгруппы, у каждой свой кабинет и преподаватель
        (ПРЕДМЕТЫ, ПРЕПОДАВАТЕЛИ, КАБИНЕТЫ),
        # метка «(подгруппы) » от старого разбора
        ("(подгруппы) 1.Практика | (лаб) | 2.Практика | (лаб)",
         "Сидоров С. С.; Петров П. П.", "101"),
        # обычный урок
        ("Математика", "Иванова А. А.", ""),
        # совместная лекция: два ведущих, один предмет
        ("Физика", "Крылова В. И.; Нуриева С. Р.", "220-1"),
        # три подгруппы
        ("1.А | 2.Б | 3.В", "Трифонов Т. Т.; Ушакова У. У.; Яковлев Я. Я.", "1 / 2 / 3"),
        # пусто
        ("", "", ""),
    ]
    for предмет, преподаватель, кабинет in случаи:
        через_utils = utils.split_glued(предмет, преподаватель, кабинет)
        через_timetable = [(ч.subject, ч.teacher, ч.room)
                           for ч in timetable.stored_parts(предмет, преподаватель, кабинет)]
        assert через_utils == через_timetable, (
            f"разбор разошёлся на {предмет!r}: {через_utils} против {через_timetable}")


def test_store_layer_stays_independent():
    """store не должен начать тянуть timetable: так его проверяет отдельный файл.

    Дублирую здесь не ради красоты, а ради связи: если когда-нибудь разбор
    переедет обратно в timetable, этот тест упадёт вместе с поиском «кто ведёт».
    """
    дерево = ast.parse(Path(ROOT / "store" / "schedules.py").read_text(encoding="utf-8-sig"))
    for узел in ast.walk(дерево):
        if isinstance(узел, ast.Import):
            assert all(a.name != "timetable" for a in узел.names)
        elif isinstance(узел, ast.ImportFrom) and not узел.level:
            assert узел.module != "timetable"


