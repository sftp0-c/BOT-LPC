async def _урок(группа, день, номер, предмет, преподаватель, кабинет):
    await db.run(
        "INSERT INTO lessons(group_code, weekday, lesson_num, subject, teacher, room, start, end) "
        "VALUES(?,?,?,?,?,?,?,?)",
        (группа, день, номер, предмет, преподаватель, кабинет, "08:00", "08:45"))


