"""Фильтр имён файлов расписания: колледж переименовывает файлы, а расписание
должно продолжать работать.

Что произошло. Колледж обновил расписание и назвал файлы не «24-26-25-20.pdf», а
«24-26-25-20 изм.pdf» (изм - изменённый). Проверка имени шла через fullmatch, то
есть требовала совпадения всего имени, и хвост « изм» ломал его. Файлы перестали
узнаваться, в базе у 25 групп из 35 остались ссылки на прежние имена.

Почему это выглядело не как «бот не узнал файл», а как «сломался сайт».
Прежние адреса отдают код 200 и НОЛЬ байт: сервер колледжа на отсутствующий файл
отвечает «успешно» и пустотой. Проверка падала на содержимом, с сообщением «по
ссылке не PDF», и это уводило в сторону сайта, а не в сторону имени файла.

Отсюда и проверки. Имена взяты не выдуманные, а настоящие, снятые со страницы
колледжа: 18 файлов, из которых бот должен взять 7.
"""
from urllib.parse import unquote, urlsplit

import pytest

import schedule_import as importer

ОСНОВАНИЕ = "https://collegelan.ru/studentam/Расписание/"


def файл(имя: str) -> str:
    return ОСНОВАНИЕ + unquote(имя)


# ── обновлённые файлы: из-за них всё и сломалось ───────────────────────────
@pytest.mark.parametrize("имя", [
    "24-26-25-20 изм.pdf",
    "25-21-25-26 изм.pdf",
    "25-27-25-31 изм.pdf",
    "26-23-26-27 изм.pdf",
    "26-28-26-31 изм.pdf",
])
def test_обновлённый_файл_узнаётся(имя: str):
    """Файл с пометкой «изм» - это всё ещё расписание, и он должен узнаваться."""
    assert importer.is_schedule_pdf(файл(имя), "") is True, (
        f"{имя} не признан расписанием. Колледж так помечает обновлённые файлы; "
        "если это снова не работает, посмотри сюда."
    )


# ── обычные файлы: не должны сломаться от нового правила ──────────────────
@pytest.mark.parametrize("имя", [
    "23-29-24-25.pdf",
    "25-32-26-22.pdf",
])
def test_обычный_файл_по_прежнему_узнаётся(имя: str):
    assert importer.is_schedule_pdf(файл(имя), "") is True


# ── то, что расписанием не является ───────────────────────────────────────
@pytest.mark.parametrize("имя,почему", [
    ("кураторы групп на 2026-2027.pdf", "кураторы"),
    ("График консультаций преподавателей 2025-2026.pdf", "график консультаций"),
    ("04.07-05.07.20222.pdf", "точки в имени"),
    ("21-26,21-2837.pdf", "запятая в имени"),
    ("15-21,16-22.pdf", "запятая в имени"),
    ("16-28.pdf", "единственная пара цифр"),
    ("18-29.pdf", "единственная пара цифр"),
])
def test_не_расписание_не_принимается(имя: str, почему: str):
    """Ослабление фильтра опасно: архивы откатывали бы студентам неделю."""
    assert importer.is_schedule_pdf(файл(имя), "") is False, f"{имя} принят, хотя это {почему}"


# ── по подписи ────────────────────────────────────────────────────────────
def test_мусор_отсекается_по_подписи_даже_при_похожем_имени():
    """Слова-отсекатели работают независимо от имени файла."""
    адрес = файл("25-21-25-26 изм.pdf")
    assert importer.is_schedule_pdf(адрес, "График консультаций") is False
    assert importer.is_schedule_pdf(адрес, "Кураторы групп") is False
    assert importer.is_schedule_pdf(адрес, "Расписание занятий") is True


# ── живой пример со всей страницы ─────────────────────────────────────────
ЖИВАЯ_СТРАНИЦА = """
<html><body>
<a href="/studentam/Расписание/23-29-24-25.pdf"></a>
<a href="/studentam/Расписание/24-26-25-20%20изм.pdf"></a>
<a href="/studentam/Расписание/25-21-25-26%20изм.pdf"></a>
<a href="/studentam/Расписание/25-27-25-31%20изм.pdf"></a>
<a href="/studentam/Расписание/25-32-26-22.pdf"></a>
<a href="/studentam/Расписание/26-23-26-27%20изм.pdf"></a>
<a href="/studentam/Расписание/26-28-26-31%20изм.pdf"></a>
<a href="/studentam/Расписание/кураторы%20групп%20на%202026-2027.pdf">Кураторы групп</a>
<a href="/studentam/Расписание/График%20консультаций%20преподавателей%202025-2026.pdf">График консультаций</a>
<a href="/studentam/Расписание/04.07-05.07.20222.pdf"></a>
<a href="/studentam/Расписание/21-26,21-2837.pdf"></a>
<a href="/studentam/Расписание/15-21,16-22.pdf"></a>
<a href="/studentam/Расписание/16-23,16-28.pdf"></a>
<a href="/studentam/Расписание/17-20,17-26.pdf"></a>
<a href="/studentam/Расписание/17-27,18-22.pdf"></a>
<a href="/studentam/Расписание/18-24,18-28.pdf"></a>
<a href="/studentam/Расписание/18-29.pdf"></a>
<a href="/studentam/Расписание/16-28.pdf"></a>
</body></html>
"""


@pytest.mark.asyncio
async def test_со_страницы_берутся_семь_файлов():
    """Ровно те 7 из 18, что нужны. Это сверка с настоящей страницей."""
    пары = importer._page_links(ЖИВАЯ_СТРАНИЦА, "https://collegelan.ru/studentam/raspisanie-zanyatiy.php")
    взято = [полный for полный, подпись in пары
             if importer.is_pdf_url(полный) and importer.is_schedule_pdf(полный, подпись)]
    имена = sorted(unquote(urlsplit(адрес).path.rsplit("/", 1)[-1]) for адрес in взято)
    assert len(взято) == 7, f"взято {len(взято)} вместо 7: {имена}"
    assert "24-26-25-20 изм.pdf" in имена, "обновлённые файлы не попали в список"
    assert not any("изм" not in имя and "консультац" not in имя
                   and "куратор" not in имя and "," not in имя
                   and "." not in имя[:-4] and len(имя.split("-")) < 3
                   for имя in имена), f"взято лишнее: {имена}"


@pytest.mark.asyncio
async def test_устаревшее_имя_всё_ещё_проходит():
    """Прежние имена без «изм» остаются валидными: старые базы и ручные ссылки."""
    assert importer.is_schedule_pdf(файл("24-26-25-20.pdf"), "") is True
