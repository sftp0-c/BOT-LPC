"""Проверка на старый формат: регрессия, которую я сам выкатил, закрыта.

Что случилось
-------------
Изменил разбор и показ расписания, выкатил на сервер - и испортил вывод для
данных, которые уже лежали в базе. В базе 1163 занятия разобраны старым кодом и
сохранены склеенными:

    subject = "Экономика отрас | (лекция)"
    room    = "105-2"

Lesson.split_parts(), когда parts пуст, собирает части из склеенной строки. Для
такой строки выходила отдельная часть «(лекция)» - без предмета, без кабинета и
без преподавателя, и студент видел:

    1. 08:00–08:45  Экономика отрас
     ауд. 105-2 · Сабирьянова А. Р.
     (лекция)          <- мусора раньше не было

Заметил я это не проверками, а выгрузкой живой базы: в проверках данные были
синтетические и уже нового формата. Правило проекта - вёрстку смотреть
настоящими данными, и я его на этот раз нарушил.

Что проверяет этот файл
1. Старая склейка «Предмет | (лекция)» даёт одну часть, а не две.
2. Подгрупповая старая склейка даёт две части, а не четыре.
3. Метка «(подгруппы) » не попадает в текст.
4. Преподаватель не печатается дважды.
5. Новый формат (с заполненными parts) ведёт себя так же.
"""
import timetable as tt


def урок(subject: str, teacher: str = "", room: str = "") -> tt.Lesson:
    """Урок из базы: parts не заполнен, всё лежит в склеенных строках."""
    return tt.Lesson(number=1, subject=subject, teacher=teacher, room=room,
                     start="08:00", end="08:45")


# ── 1. простая старая склейка ──────────────────────────────────────────────
def test_старый_формат_даёт_одну_часть():
    """«Экономика отрас | (лекция)» - это один предмет, а не два."""
    части = урок("Экономика отрас | (лекция)", "Сабирьянова А. Р.", "105-2").split_parts()

    assert len(части) == 1, f"частей {len(части)}, ждали 1: {части}"
    assert части[0].subject == "Экономика отрас (лекция)", части[0].subject
    assert части[0].teacher == "Сабирьянова А. Р.", части[0].teacher
    assert части[0].room == "105-2", части[0].room


def test_старый_формат_без_вида_занятия():
    """Предмет без склейки остаётся как есть."""
    части = урок("Математика", "Иванова А. А.", "204").split_parts()

    assert len(части) == 1
    assert части[0].subject == "Математика", части[0].subject


def test_старый_формат_в_тексте_без_мусора():
    """В показанной строке не должно быть висячей «(лекция)»."""
    текст = урок("Экономика отрас | (лекция)", "Сабирьянова А. Р.", "105-2").line()

    assert "Экономика отрас (лекция)" in текст, текст
    assert "ауд. 105-2 · Сабирьянова А. Р." in текст, текст
    строки = [x.strip() for x in текст.split("\n")]
    assert not any(s == "(лекция)" for s in строки), текст


# ── 2. подгрупповая старая склейка ────────────────────────────────────────
def test_старые_подгруппы_дают_две_части():
    """Старая подгрупповая склейка режется на четыре - должна на две."""
    части = урок(
        "(подгруппы) 1.ИнженерКомпГраф | (лабораторная) | "
        "2.ИнЯзык в ПрофД | (лабораторная)",
        "Павлова В. В.; Мухамадеева Л. Р.", "205-2").split_parts()

    assert len(части) == 2, f"частей {len(части)}, ждали 2: {части}"
    assert части[0].subject == "1.ИнженерКомпГраф (лабораторная)", части[0].subject
    assert части[1].subject == "2.ИнЯзык в ПрофД (лабораторная)", части[1].subject


def test_метка_подгрупп_не_попадает_в_показ():
    """«(подгруппы) » - служебная метка, в тексте расписания ей не место.

    Номер «1.» и так говорит, что это подгруппа, а лишнее слово в скобках мешает
    читать - владелец просил понятно на глаз.
    """
    текст = урок(
        "(подгруппы) 1.ИнженерКомпГраф | (лабораторная) | "
        "2.ИнЯзык в ПрофД | (лабораторная)",
        "Павлова В. В.; Мухамадеева Л. Р.", "205-2").line()

    assert "(подгруппы)" not in текст, текст
    assert "1.ИнженерКомпГраф (лабораторная)" in текст, текст


def test_преподаватель_не_печатается_дважды():
    """Каждый преподаватель - в своей строке, один раз.

    Был код, который склеивал всех преподавателей в первую часть, и второй
    печатался дважды: в первой строке и в своей.
    """
    текст = урок(
        "(подгруппы) 1.ИнженерКомпГраф | (лабораторная) | "
        "2.ИнЯзык в ПрофД | (лабораторная)",
        "Павлова В. В.; Мухамадеева Л. Р.", "205-2").line()

    assert текст.count("Павлова В. В.") == 1, текст
    assert текст.count("Мухамадеева Л. Р.") == 1, текст
    assert текст.index("Павлова В. В.") < текст.index("Мухамадеева Л. Р."), текст


# ── 3. новый формат не пострадал ──────────────────────────────────────────
def test_новый_формат_с_parts_не_склеивается():
    """Когда части заполнены (новый разбор), склейка не применяется."""
    готовый = tt.Lesson(
        number=1,
        subject="1.ТРТОУ (лабораторная) | 2.ПрофД (лабораторная)",
        teacher="Ибрагимов Р. Т.; Власова Л. Н.",
        room="РММ / 313-1",
        parts=[tt.LessonPart("1.ТРТОУ (лабораторная)", "Ибрагимов Р. Т.", "РММ"),
               tt.LessonPart("2.ПрофД (лабораторная)", "Власова Л. Н.", "313-1")])

    части = готовый.split_parts()

    assert len(части) == 2, части
    assert части[0].room == "РММ", части[0].room
    assert части[1].room == "313-1", части[1].room


def test_аудитория_со_слешем_в_одном_значении_не_ломается():
    """«214/215» - один кабинет, а не два.

    Разделитель аудиторий - « / » с пробелами, поэтому «214/215» без пробелов
    остаётся одним значением.
    """
    части = урок("Математика (лекция)", "Иванова А. А.", "214/215").split_parts()

    assert len(части) == 1
    assert части[0].room == "214/215", части[0].room


