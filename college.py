def setting_key(key: str) -> str:
    """Ключ настройки для поля справочника: «college:адрес»."""
    return f"{PREFIX}{key}"


async def get(key: str) -> str:
    """Значение поля: сначала переопределение из панели, потом данные с сайта."""
    value = as_str(await db.get_setting(setting_key(key))).strip()
    return value or as_str(DEFAULTS.get(key, "")).strip()


async def override(key: str, value: str) -> None:
    """Сохранить переопределение поля из панели. Пустое значение = вернуть данные с сайта."""
    if key not in DEFAULTS:
        log.warning("справочник колледжа: неизвестное поле %r, переопределение не сохранено", key)
        return
    value = as_str(value).strip()[:MAX_VALUE]
    if value:
        await db.set_setting(setting_key(key), value)
        log.info("справочник колледжа: поле %s переопределено из панели", key)
        return
    await db.run("DELETE FROM settings WHERE key=?", (setting_key(key),))
    log.info("справочник колледжа: поле %s возвращено к данным с сайта", key)


async def is_overridden(key: str) -> bool:
    """Есть ли переопределение из панели (для подсказки в панели)."""
    return bool(as_str(await db.get_setting(setting_key(key))).strip())


async def contacts() -> dict[str, str]:
    """Все поля справочника одним словарём — так удобно показать их в боте."""
    return {key: await get(key) for key in FIELDS}


async def text(fields: tuple[str, ...] | None = None) -> str:
    """Справочник текстом: «адрес: …», «телефон приёмная: …» и так далее.

    По умолчанию берётся MENU_FIELDS - столько влезает в одно сообщение MAX.
    С fields можно вывести любой свой набор (пустое значение показывается
    прочерком, чтобы дыра в данных была видна), а fields=FIELDS - весь справочник
    целиком: в панели он идёт в несколько сообщений.
    """
    wanted = MENU_FIELDS if fields is None else fields
    lines = [f"{key.replace('_', ' ')}: {await get(key) or '—'}" for key in wanted]
    return "\n".join(["🏫 Лангепасский политехнический колледж", *lines])


