"""Отдельная служба моста: только служебные адреса, только локально.

Зачем вторая служба, если есть основная. Коротко: проверка «запрос с этой
машины» внутри бота не работает, и я это обнаружил не умозрительно, а запуском.

Что происходит. Бот слушает порт 8080, и Docker публикует его на 0.0.0.0 -
так доступна панель из локальной сети. Но Docker Desktop на Windows идёт через
машину в виртуальной среде, и опубликованный порт перебрасывает запрос так,
что бот видит адрес не 127.0.0.1, а шлюз этой виртуальной сети. Проверка
«клиент с этой машины» отвечает отказом на ЛЮБОЙ запрос извне контейнера -
включая тот самый, который делает мост с этой же машины.

Значит, такую проверку внутри приложения держать нельзя: она либо всегда
отказывает мосту, либо, если её ослабить до «шлюза виртуальной сети», не
проверяет ничего (любой из сети выглядит так же).

Где граница держится по-настоящему. На хосте. Порт 8090 публикуется как
`127.0.0.1:8090:8090`, и операционная система просто не принимает на нём
соединения из сети. Это проверка на уровне системы, подделать её извне нельзя,
и ей не мешает то, как Docker переписывает адреса.

Что остаётся внутри. Токен. Он по-прежнему обязателен: порт закрыт снаружи,
но любой процесс на этой машине до него дотягивается, а программа моста -
единственный, кому это нужно.

Чего в этой службе нет. Ни панели, ни входа, ни данных об обращениях. Это
четыре адреса очереди и всё. Отдельное приложение, а не подключение к
существующему, - именно поэтому служебные адреса нельзя вызвать через порт 8080.
"""
import repository as repo                                            # noqa: F401 - ради регистрации web.bridge
from fastapi import FastAPI

import config
from web import bridge as bridge_routes                              # noqa: F401 - регистрация адресов

app = FastAPI(title="Мост: служебные адреса", docs_url=None, redoc_url=None,
              openapi_url=None)

# Только служебные адреса моста. Никаких страниц панели: этот порт не должен
# отдавать наружу ничего, кроме очереди.
app.include_router(bridge_routes.router)


@app.get("/health")
async def health() -> dict:
    """Живость службы. Без токена и без данных: только факт, что она отвечает."""
    return {"ok": True, "service": "bridge", "enabled": config.BRIDGE_ENABLED}
