"""Проверка подписи MAX для мини-приложения.

Откуда взялось
-------------
MAX кладёт в адрес страницы фрагмент вида

    #WebAppData=...&WebAppPlatform=web&WebAppVersion=26.2.8

Фрагмент (после #) браузер на сервер не отправляет, поэтому подпись проверять
на backend иначе нечем: страницу отдаёт сам веб, а она потом просит наш API о
данных. Значит клиент передаёт нам `initData` из `window.WebApp.initData`, и мы
проверяем подпись сами.

Подпись та же, что в Telegram: HMAC-SHA256 от отсортированных параметров, ключ
считается из токена бота. Только названия другие.

Что здесь важно не перепутать
-----------------------------
Декодирование двухуровневое, и это главная ловушка:

* `#WebAppData=<строка>` — внешний слой percent-кодирования;
* внутри строки значения снова закодированы: `user=%7B%22id%22%3A67890...%7D`.

Браузер разворачивает внешний слой сам, когда отдаёт `initData`. Поэтому сюда
приходит строка, где пары разделены `&`, а значения ещё закодированы, и их надо
развернуть РОВНО один раз. Если развернуть дважды, получится мусор, а если ни
разу — подпись не сойдётся.

Параметр `hash` в подпись не входит: он и есть результат, который сравнивают.

Про срок жизни
--------------
`auth_date` проверяем на наличие, но не отбрасываем по возрасту: MAX не задаёт
максимальный срок, а придумать свой — значит однажды отрезать живых
пользователей. Для данных, которые только читаются, это не опасно; если
появится что-то, меняющее состояние, срок понадобится и его надо будет задать
явно.

Модуль ничего не знает про FastAPI и про веб - только про подпись. Роут для
мини-приложения будет отдельным.
"""
import hashlib
import hmac
import json
from urllib.parse import unquote

from utils import as_str

# Строка-ключ, которой MAX подписывает токен бота. Изменять нельзя: значение
# задаёт платформа, а не мы.
KEY_CONSTANT = b"WebAppData"


def secret_key(bot_token: str) -> bytes:
    """Ключ проверки подписи из токена бота.

    MAX: подписать токен бота, используя строку «WebAppData» как ключ. То есть
    сообщение - токен, ключ - KEY_CONSTANT. Порядок аргументов у hmac.new
    обратный привычному чтению, поэтому здесь он записан явно.
    """
    return hmac.new(KEY_CONSTANT, as_str(bot_token).encode("utf-8"), hashlib.sha256).digest()


def _pairs(init_data: str) -> list:
    """Пары key=value из initData, значения развёрнуты ровно один раз.

    Именно список, а не словарь: повторяющийся ключ обязан остаться виден, иначе
    проверка подписи посчитает не ту строку, которую прислали.
    """
    пары: list = []
    for кусок in as_str(init_data).split("&"):
        if not кусок or "=" not in кусок:
            continue
        ключ, _, значение = кусок.partition("=")
        пары.append((unquote(ключ), unquote(значение)))
    return пары


def повторяются_ли_ключи(init_data: str) -> bool:
    """Встретился ли один ключ дважды.

    Требование документации MAX. Словарь повтор теряет, поэтому проверять надо
    по исходному списку пар.
    """
    ключи = [ключ for ключ, _значение in _pairs(init_data)]
    return len(ключи) != len(set(ключи))


def parse(init_data: str) -> dict:
    """Разбирает initData в словарь параметров со снятым внешним кодом.

    Значения разворачиваются ровно один раз. Словарь годится для чтения
    user/chat, но для подписи он непригоден - бери data_check_string поверх
    исходной строки.
    """
    return dict(_pairs(init_data))


def data_check_string(параметры: dict) -> str:
    """Строка, которую MAX подписывает: пары по алфавиту, через перевод строки.

    `hash` из параметров исключается: он и есть результат подписи.
    """
    пары = [f"{ключ}={значение}" for ключ, значение in sorted(параметры.items())
            if ключ != "hash"]
    return "\n".join(пары)


def sign(init_data: str, bot_token: str) -> str:
    """Подпись для init_data. Нужна и для проверки, и для проверяющих тестов."""
    подпись = hmac.new(secret_key(bot_token),
                       data_check_string(parse(init_data)).encode("utf-8"),
                       hashlib.sha256).hexdigest()
    return подпись


def verify(init_data: str, bot_token: str) -> dict | None:
    """Проверяет подпись. Возвращает параметры или None, если данные не наши.

    None, а не исключение: неверная подпись - это обычное дело (старый адрес,
    чужая ссылка), а не поломка. Решать, что показать, должен вызывающий.
    """
    if not bot_token:
        return None
    if повторяются_ли_ключи(init_data):
        return None
    параметры = parse(init_data)
    присланный = as_str(параметры.get("hash"))
    if not присланный:
        return None
    ожидаемый = sign(init_data, bot_token)
    # Сравниваем байты, а не строки: hmac.compare_digest отказывается работать
    # с не-ASCII и бросает TypeError, а присланный hash берётся из чужого
    # запроса. Без этого клиент с мусором в подписи получил бы 500 вместо
    # отказа. Сравнение постоянного времени нужно, чтобы по скорости ответа
    # нельзя было подбирать подпись побайтно.
    if not hmac.compare_digest(ожидаемый.encode("ascii"),
                               присланный.encode("utf-8", "replace")):
        return None
    return параметры


def user_id(параметры: dict) -> str:
    """MAX ID человека, открывшего мини-приложение. Пустая строка, если нет.

    В базе ID лежит строкой, поэтому приводим к строку сразу, чтобы по дороге
    не забыть и не сравнить 67890 с "67890".
    """
    сырое = as_str(параметры.get("user"))
    if not сырое:
        return ""
    try:
        человек = json.loads(сырое)
    except (ValueError, TypeError):
        return ""
    if not isinstance(человек, dict):
        return ""
    return as_str(человек.get("id"))


def start_param(параметры: dict) -> str:
    """Значение из ?startapp= - что открыть при запуске (группа, обращение)."""
    return as_str(параметры.get("start_param"))


def проверка(init_data: str, bot_token: str) -> tuple[str, dict]:
    """Проверяет подпись и достаёт ID. Бросает ValueError, если человек чужой.

    Удобная обёртка для роутов: проверка и разбор в одном месте, чтобы в
    обработчике нельзя было забыть про подпись.
    """
    параметры = verify(init_data, bot_token)
    if not параметры:
        raise ValueError("подпись MAX не подтверждена")
    человек = user_id(параметры)
    if not человек:
        raise ValueError("в подписи нет пользователя")
    return человек, параметры