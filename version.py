"""Версия проекта: единственное место, где она живёт в коде.

Значение берётся из файла VERSION в корне репозитория, а не зашито строкой:
иначе файл и код разъедутся, и это заметят только пользователи. Если файла нет
(сборка из старого копирования, запу��к вне репозитория) - отдаём "неизвестно"
и не падаем: проверка версии не должна ронять бот.
"""
from pathlib import Path

UNKNOWN = "неизвестно"


def read() -> str:
    """Версия из файла VERSION. Пустая строка, если файла нет или он пуст."""
    try:
        value = Path(__file__).with_name("VERSION").read_text(encoding="utf-8-sig").strip()
    except OSError:
        return UNKNOWN
    return value or UNKNOWN


__version__ = read()
"""Версия проекта, например "1.1.0"."""
